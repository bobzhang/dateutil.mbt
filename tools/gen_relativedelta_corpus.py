rnd = random.Random(20261001)
out = ['// Generated by tools/gen_relativedelta_corpus.py from python-dateutil; do not edit.\n']

WD = ['mo', 'tu', 'we', 'th', 'fr', 'sa', 'su']


def mbt_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def fl(v):
    r = repr(float(v))
    if 'e' in r:
        m, e = r.split('e')
        if '.' not in m:
            m += '.0'
        r = m + 'e' + e
    return r


def emit(name, lines):
    out.append('///|\ntest "%s" {\n%s\n}\n' % (name, '\n'.join('  ' + l for l in lines)))


def outcome(f):
    try:
        r = f()
    except (ValueError, OverflowError) as e:
        return type(e).__name__ if not isinstance(e, ValueError) else 'ValueError'
    return repr(r)


