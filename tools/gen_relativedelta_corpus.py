# random relativedeltas


def rand_weekday():
    k = rnd.randrange(7)
    n = rnd.choice([None, None, 0, 1, -1, 2, -2, 3, -3, 5, -5])
    py = weekdays[k](n)
    if n is None:
        mb = '@relativedelta.%s' % WD[k]
    else:
        mb = '@relativedelta.%s.nth(Some(%d))' % (WD[k], n)
    return py, mb


def rand_rd(floaty=None, allow_yearday=True):
    """Return (python relativedelta or exception name, MoonBit constructor)."""
    if floaty is None:
        floaty = rnd.random() < 0.35
    kw = {}
    mb = []
    if rnd.random() < 0.5:
        kw['years'] = rnd.choice([rnd.randint(-3, 3), rnd.randint(-300, 300)])
    if rnd.random() < 0.5:
        kw['months'] = rnd.choice([rnd.randint(-13, 13), rnd.randint(-400, 400)])
    for k, lo, hi in [('days', -400, 400), ('weeks', -60, 60), ('hours', -50, 50),
                      ('minutes', -200, 200), ('seconds', -5000, 5000),
                      ('microseconds', -3000000, 3000000)]:
        if rnd.random() < 0.3:
            if floaty and rnd.random() < 0.7:
                kw[k] = round(rnd.uniform(lo, hi) / rnd.choice([1, 7, 30]), rnd.choice([1, 2, 3, 6]))
            else:
                kw[k] = rnd.randint(lo, hi)
    if rnd.random() < 0.15:
        kw['leapdays'] = rnd.choice([-1, 1, 2])
    for k, vals in [('year', lambda: rnd.choice([0, rnd.randint(1, 9999), rnd.randint(1990, 2030)])),
                    ('month', lambda: rnd.choice([0, rnd.randint(1, 12), rnd.randint(1, 12)])),
                    ('day', lambda: rnd.choice([0, -1, rnd.randint(1, 31), rnd.randint(28, 31)])),
                    ('hour', lambda: rnd.randint(0, 23)),
                    ('minute', lambda: rnd.randint(0, 59)),
                    ('second', lambda: rnd.randint(0, 59)),
                    ('microsecond', lambda: rnd.randint(0, 999999))]:
        if rnd.random() < 0.12:
            kw[k] = vals()
    wd_mb = None
    if rnd.random() < 0.3:
        kw['weekday'], wd_mb = rand_weekday()
    if allow_yearday and rnd.random() < 0.08:
        kw[rnd.choice(['yearday', 'nlyearday'])] = rnd.choice(
            [rnd.randint(1, 366), rnd.randint(55, 65), 367, -3])
    for k, v in kw.items():
        if k == 'weekday':
            mb.append('weekday=%s' % wd_mb)
        elif floaty and k in ('years', 'months', 'days', 'weeks', 'hours',
                              'minutes', 'seconds', 'microseconds'):
            mb.append('%s=%s' % (k, fl(v)))
        else:
            mb.append('%s=%d' % (k, v))
    ctor = 'from_float' if floaty else 'new'
    call = '@relativedelta.RelativeDelta::%s(%s)' % (ctor, ', '.join(mb))
    try:
        py = relativedelta(**{k: (float(v) if floaty and k in ('years', 'months') else v)
                              for k, v in kw.items()})
    except ValueError:
        py = 'ValueError'
    return py, call


def rand_valid_rd(**k):
    while True:
        py, mb = rand_rd(**k)
        if not isinstance(py, str):
            return py, mb


